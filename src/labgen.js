function g2(sex, m, f) { return sex === 'F' ? f : m; }
const pickR = (spec, sex, edge) => { const s = Array.isArray(spec) ? spec : spec[sex]; return edge ? s[1] : s[0]; };
const ri = (r, a, b) => Math.floor(a + r() * (b - a + 1));

/* מחשב קריאטינין מתוך eGFR יעד (הפוך לנוסחה) ומחזיר גם את ה-eGFR המוצג שמתאים לערך המעוגל */
function creaFor(lo, hi, age, sex, r) {
  let best = null;
  for (let t = 0; t < 80; t++) {
    const target = between(lo, hi, r);
    let a = .3, b = 14; for (let i = 0; i < 40; i++) { const m = (a + b) / 2; if (calcEgfr(m, age, sex) > target) a = m; else b = m; }
    const crea = Math.round(((a + b) / 2) * 10) / 10, e = calcEgfr(crea, age, sex);
    if (e >= lo && e <= hi) return { crea, e };
    best = { crea, e };
  }
  return best;
}
function genNeph(type, r = Math.random, o = {}) {
  const S = SPEC[type], edge = !!o.edge, sex = S.sex(r), age = Math.round(between(S.age[0], S.age[1], r));
  const v = {};
  const sample = (k) => { const b = BASEV[k], s = S.f[k] ? pickR(S.f[k], sex, edge) : (Array.isArray(b) ? b : b[sex]); return between(s[0], s[1], r); };
  ['UREA', 'NA', 'K', 'HCO3', 'PH', 'CA', 'PHOS', 'PTH', 'URIC', 'Hb', 'WBC', 'CRP', 'GLU', 'UPCR', 'USG'].forEach(k => v[k] = sample(k));
  const ce = creaFor(S.eg[edge ? 1 : 0][0], S.eg[edge ? 1 : 0][1], age, sex, r); v.CREA = ce.crea; v.EGFR = ce.e;
  Object.keys(v).forEach(k => { if (LAB[k]) v[k] = round(v[k], LAB[k].d); });
  const d = S.dip, dip = { leuk: d.leuk ? ri(r, d.leuk[0], d.leuk[1]) : 0, nit: d.nit ? 1 : 0, blood: d.blood ? ri(r, d.blood[0], d.blood[1]) : 0, prot: d.prot ? ri(r, d.prot[0], d.prot[1]) : 0, glu: d.glu ? ri(r, d.glu[0], d.glu[1]) : 0 };
  const u = S.uvol[edge ? 1 : 0], uvol = Math.round(between(u[0], u[1], r) / 10) * 10;
  return { type, edge, sex, age, vals: v, dip, us: S.us, uvol, complaint: pick(S.cm(sex), r) };
}

/* ===== המסווג ("האמת"): אבחנה יחידה שעולה מהערכים, בלי הסיפור ===== */
function classifyNeph(p) {
  const v = p.vals, d = p.dip;
  if (v.EGFR < 60) {
    if (p.us === 'small') return 'ckd';
    if (p.us === 'hydro') return 'postrenal';
    return v.USG >= 1.020 ? 'prerenal' : 'renal_aki';
  }
  if (v.NA >= 146 && v.USG <= 1.007) return 'di';
  if (p.us === 'stone') return 'stone';
  if (v.WBC > 11 || v.CRP > 20) return 'pyelo';
  if (d.leuk >= 3 && d.nit) return 'cystitis';
  if (v.GLU >= 126 && v.UPCR > 150) return 'diabetic';
  return null;
}
